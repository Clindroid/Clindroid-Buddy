import path from "path"
import { fileURLToPath } from "url"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const dir = path.resolve(__dirname, "..")

process.chdir(dir)

await import("./generate-skills.ts")

const modelsUrl = process.env.CLINBUDDY_MODELS_URL || "https://models.dev"
// ClindroidBuddy only supports these providers (plus locally-configured
// ones like ollama, which don't come from models.dev) - keep the shipped
// snapshot restricted to them instead of embedding the entire models.dev
// catalog of 100+ hosted providers.
const ALLOWED_PROVIDERS = ["openai", "github-copilot", "anthropic", "google", "amazon-bedrock", "nvidia"]
// Fetch and generate models.dev snapshot
const modelsDataRaw = process.env.MODELS_DEV_API_JSON
  ? await Bun.file(process.env.MODELS_DEV_API_JSON).text()
  : await fetch(`${modelsUrl}/api.json`).then((x) => x.text())
const modelsData = JSON.stringify(
  Object.fromEntries(
    Object.entries(JSON.parse(modelsDataRaw)).filter(([id]) => ALLOWED_PROVIDERS.includes(id)),
  ),
)
await Bun.write(
  path.join(dir, "src/provider/models-snapshot.js"),
  `// @ts-nocheck\n// Auto-generated by build.ts - do not edit\nexport const snapshot = ${modelsData}\n`,
)
await Bun.write(
  path.join(dir, "src/provider/models-snapshot.d.ts"),
  `// Auto-generated by build.ts - do not edit\nexport declare const snapshot: Record<string, unknown>\n`,
)
console.log("Generated models-snapshot.js")
