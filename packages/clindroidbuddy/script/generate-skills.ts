#!/usr/bin/env bun

// `bun build --compile` only bundles JS reachable from the entrypoints, so the
// built-in skills under src/skill/skills/** never make it into the binary and
// Skill discovery finds nothing but the user's global ~/.claude/skills. Embed
// them as a generated module instead; src/skill/index.ts writes the snapshot
// back out to a real directory at runtime.
import path from "path"
import { fileURLToPath } from "url"

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const root = path.join(dir, "src/skill/skills")

const files = (await Array.fromAsync(new Bun.Glob("**/*").scan({ cwd: root })))
  .map((file) => file.replaceAll("\\", "/"))
  .sort()

const skills = new Set(files.filter((file) => file.endsWith("/SKILL.md")).map((file) => file.split("/")[0]))
for (const entry of new Set(files.map((file) => file.split("/")[0]))) {
  if (!skills.has(entry)) throw new Error(`built-in skill "${entry}" has no SKILL.md`)
}

const snapshot: Record<string, string> = {}
for (const file of files) {
  snapshot[file] = await Bun.file(path.join(root, file)).text()
}

await Bun.write(
  path.join(dir, "src/skill/skills-snapshot.js"),
  `// @ts-nocheck\n// Auto-generated by script/generate-skills.ts - do not edit\nexport const snapshot = ${JSON.stringify(snapshot)}\n`,
)
await Bun.write(
  path.join(dir, "src/skill/skills-snapshot.d.ts"),
  `// Auto-generated by script/generate-skills.ts - do not edit\nexport declare const snapshot: Record<string, string>\n`,
)
console.log(`Generated skills-snapshot.js (${skills.size} skills, ${files.length} files)`)
